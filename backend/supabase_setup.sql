-- Run once in Supabase SQL Editor to set up the RAG vector store.

create extension if not exists vector;

create table if not exists document_chunks (
  id bigint generated by default as identity primary key,
  user_id text not null,
  source text not null,
  content text not null,
  embedding vector(384) not null,
  created_at timestamptz not null default now()
);

create index if not exists document_chunks_user_id_idx on document_chunks (user_id);

create index if not exists document_chunks_embedding_idx on document_chunks
  using hnsw (embedding vector_cosine_ops);

-- RPC used by the backend for similarity search (pgvector's <=> operator
-- isn't reachable through the normal PostgREST table filters).
--
-- Mode-aware similarity search for chat retrieval.
-- source_mode = 'server' searches only the shared admin-curated library.
-- source_mode = 'local' searches only the calling user's uploaded documents.
-- source_mode = 'hybrid' searches both and ranks them together.
create or replace function match_document_chunks(
  query_embedding vector(384),
  match_user_id text,
  match_count int default 4,
  source_mode text default 'hybrid'
)
returns table (
  id bigint,
  source text,
  content text,
  similarity float,
  source_kind text
)
language sql stable
as $$
  select
    document_chunks.id,
    document_chunks.source,
    document_chunks.content,
    1 - (document_chunks.embedding <=> query_embedding) as similarity,
    case
      when document_chunks.user_id = 'global-knowledge-base' then 'server'
      else 'local'
    end as source_kind
  from document_chunks
  where
    case
      when source_mode = 'server' then document_chunks.user_id = 'global-knowledge-base'
      when source_mode = 'local' then document_chunks.user_id = match_user_id
      else document_chunks.user_id = match_user_id or document_chunks.user_id = 'global-knowledge-base'
    end
  order by document_chunks.embedding <=> query_embedding
  limit match_count;
$$;
